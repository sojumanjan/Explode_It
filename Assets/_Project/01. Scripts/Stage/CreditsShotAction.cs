namespace ExplodeIt.Stage
{
    // 크레딧 장면에서 배우 그림 하나가 하는 짧은 트윈 동작.
    public enum CreditsShotAction
    {
        // 움직이지 않고 그림만 바꾼다.
        None,
        // 뽀잉 하고 커졌다 돌아온다. 세기 = 커지는 비율.
        Punch,
        // 부르르 떤다. 세기 = 좌우로 흔들리는 폭 (유닛). 횟수 = 흔들림 수 배율(1초쯤에 1, 길게 떨면 길이만큼 늘린다).
        Shake,
        // 콩콩 뛴다. 세기 = 뛰는 높이 (유닛), 횟수만큼. 이동을 주면 뛰면서 그만큼 옮겨 간다(낮게 여러 번 뛰면 걷기).
        Hop,
        // 그만큼 옮겨 간다. 이동 = 옮길 거리 (유닛).
        Move,
        // 좌우를 뒤집어 반대쪽을 본다.
        Flip,
        // 쏙 작아지며 사라진다(구멍에 빠지기, 땅속으로 들어가기).
        Vanish,
        // 0에서 커지며 나타난다. 씬에서 꺼 둔 배우도 이때 켜진다.
        Appear
    }
}
