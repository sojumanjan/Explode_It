namespace ExplodeIt.Core
{
    // 승천 저주 종류. 저장에는 저주 데이터의 ID가 남으므로 순서를 바꿔도 되지만, 이름은 시스템들이 읽으니 바꾸지 않는다.
    public enum CurseKind
    {
        // 스폰 간격이 줄고 모든 적이 처음부터 최대 가중치로 나온다.
        Onslaught,
        // 적이 죽은 자리에 예고 원 뒤 폭발. 플레이어만 맞는다.
        ChainBlast,
        // 플레이어 근처에 주기적으로 운석이 떨어진다. 적도 맞는다.
        MeteorRain,
        // 낮은 확률로 붉게 빛나는 매우 빠른 적.
        Berserk,
        // 주기적으로 매우 넓은 범위에 번개.
        Lightning,
        // 일부 적이 구역 대신 플레이어 근처 무작위 위치에 나온다.
        Ambush,
        // 플레이어 근처에 주기적으로 덫이 깔린다.
        Trap,
        // 체력 1칸.
        OneHit,
        // 맵에 플레이어를 느리게 하는 영역.
        Swamp,
        // 마지막 칸. 저주가 아니라 모든 저주를 낀 채 각성한 왕과 바로 싸우는 입장권이다.
        King
    }
}
